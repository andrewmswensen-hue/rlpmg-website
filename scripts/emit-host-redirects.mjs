/**
 * Emit host-level redirect rules so production serves real 301s.
 *
 * On a static host Astro can only emit a meta-refresh stub for each redirect.
 * That works, and it carries a canonical, but Google treats a meta refresh as a
 * soft redirect: slower to follow and weaker at passing link equity than a real
 * 301. With 62 redirects, 53 of them consolidating posts that carry up to eight
 * years of authority, the difference is worth having.
 *
 * Writes both formats so whichever host is chosen just works:
 *   dist/_redirects   Cloudflare Pages and Netlify
 *   dist/vercel.json  Vercel
 *
 * GitHub Pages supports neither, so the preview keeps using the meta-refresh
 * stubs. Those stay in place as the fallback either way.
 */
import { writeFile } from 'node:fs/promises';
import { redirects } from '../src/data/redirects.mjs';

const entries = Object.entries(redirects);

// _redirects: one rule per line, "from to status"
const lines = [
  '# Generated by scripts/emit-host-redirects.mjs. Do not edit by hand.',
  '# Real 301s, so consolidated pages pass their link equity to the survivor.',
  '',
  ...entries.map(([from, r]) => `${from}  ${r.destination}  ${r.status ?? 301}`),
  '',
  '# Trailing-slash safety: the site is built with trailingSlash "always".',
  '/*  /:splat/  301',
  '',
];
await writeFile('dist/_redirects', lines.join('\n'));

// vercel.json equivalent
await writeFile('dist/vercel.json', JSON.stringify({
  redirects: entries.map(([source, r]) => ({
    source, destination: r.destination, permanent: (r.status ?? 301) === 301,
  })),
  trailingSlash: true,
}, null, 2));

console.log(`host redirects: ${entries.length} rules written to dist/_redirects and dist/vercel.json`);
